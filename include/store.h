#ifndef NEO_STORE_H
#define NEO_STORE_H

#include <nitekernel.h>
#include <devices.h>

/* One downloadable driver package in the store. */
struct store_entry {
    const char *name;
    const char *kind;         /* mesa-dri, mesa-glx, ... */
    const char *vendor;
    const char *file;         /* payload file name */
    const char *version;
    const char *sha256;       /* expected digest, lowercase hex */
    const char *url;          /* upstream fallback URL */
    const char *provides;
    u32  size;
    u16  class_code;          /* PCI class to match (0 = any) */
    u16  vendor_id;           /* PCI vendor to match (0 = any) */
    u16  device_id;           /* PCI device to match (0 = any) */
    int  priority;
};

/* Generated by tools/build_store.py and linked in. */
extern const struct store_entry g_store_entries[];
extern const u32 g_store_count;
extern const char g_store_mirror[];

/* A driver recorded in the on-disk database. */
struct driver_record {
    char name[32];
    char kind[16];
    char version[16];
    char sha256[65];
    char file[32];
    u32  size;
    u16  vendor_id;
    u16  device_id;
    u16  class_code;
    int  loaded;
};

#define DRIVER_DB_MAX 24

void store_init(void);
u32  store_entry_count(void);
const struct store_entry *store_entry(u32 index);

/* Does the entry match any discovered device? Returns the matching device or NULL. */
const struct pci_device *store_match(const struct store_entry *e, const struct hw_profile *hw);

/* Full first-boot acquisition: match, download, verify, persist.
   Returns the number of drivers installed. */
int  store_acquire(const struct hw_profile *hw);

/* Driver database (persisted on NEOFS). */
int  driverdb_load(void);
int  driverdb_save(void);
int  driverdb_count(void);
const struct driver_record *driverdb_get(int index);
int  driverdb_has(const char *name);
void driverdb_print(void);

/* Download a single URL into a heap buffer (caller frees). */
int  store_download(const char *url, u8 **out, u32 *out_len);

#endif
