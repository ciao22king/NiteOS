#ifndef NEO_APPSTORE_H
#define NEO_APPSTORE_H

#include <nitekernel.h>

/* The app store: `lash install <name>` picks the package format this machine
   can actually run, downloads it, verifies its SHA-256 and stores it on NEOFS.

   Formats are ranked when an app publishes more than one: a native .lash
   package wins, then a PE32+ .exe (the Windows loader), then a type-2 AppImage
   (the ELF loader), then a plain ELF. A .dmg is a macOS disk image and is never
   selected; it stays in the catalogue so the store can say why. */

enum app_format {
    APP_FMT_LASH = 0,
    APP_FMT_EXE,
    APP_FMT_APPIMAGE,
    APP_FMT_ELF,
    APP_FMT_DMG,
    APP_FMT_COUNT
};

struct app_candidate {
    const char *file;        /* name to store on NEOFS, e.g. "hello.lash" */
    const char *url;         /* upstream fallback, may be empty */
    const char *sha256;      /* expected digest; empty = not installable */
    u32  size;
    u8   format;             /* APP_FMT_* */
};

struct app_entry {
    const char *name;
    const char *version;
    const char *summary;
    const struct app_candidate *candidates;
    u32 candidate_count;
};

/* Generated by tools/build_appstore.py and linked in. */
extern const struct app_entry g_app_entries[];
extern const u32 g_app_count;
extern const char g_app_mirror[];

u32 app_count(void);
const struct app_entry *app_at(u32 index);

/* Exact name match first, then a unique case-insensitive substring match, so
   `install hell` still finds "hello". NULL when nothing (or more than one)
   matches. */
const struct app_entry *app_find(const char *name);

/* The candidate this machine should install, or NULL if none is runnable. */
const struct app_candidate *app_best(const struct app_entry *e);

const char *app_format_name(u8 fmt);
/* `run <file>`-style hint for an installed package. */
const char *app_format_runner(u8 fmt);

void app_print_catalog(const char *needle);

/* Download, verify and persist one app. Returns 0 on success (or if it was
   already installed). */
int app_install(const char *name);

#endif
