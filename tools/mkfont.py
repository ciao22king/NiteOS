#!/usr/bin/env python3
"""Convert a PSF1 8x16 console font into a C header for the kernel's
framebuffer text renderer.

PSF1 stores each glyph row with bit 0 as the leftmost pixel; the kernel
renderer draws with bit 7 as leftmost, so every byte is bit-reversed here.
"""
import gzip
import sys

def load_psf1(path):
    data = gzip.open(path, "rb").read() if path.endswith(".gz") else open(path, "rb").read()
    magic = data[:2]
    if magic != b"\x36\x04":
        raise SystemExit("not a PSF1 font: %s" % magic.hex())
    charsize = data[3]
    if charsize != 16:
        raise SystemExit("expected 16-byte glyphs, got %d" % charsize)
    body = data[4:]
    return [body[i * 16:(i + 1) * 16] for i in range(256)]

REV = [int(f"{i:08b}"[::-1], 2) for i in range(256)]

def emit(glyphs, out_path):
    with open(out_path, "w") as f:
        f.write("/* Generated by tools/mkfont.py - do not edit. */\n")
        f.write("#ifndef NEO_FONT8X16_H\n#define NEO_FONT8X16_H\n\n")
        f.write("#include <nitekernel.h>\n\n")
        f.write("static const u8 font8x16[256][16] = {\n")
        for i, g in enumerate(glyphs):
            rows = ", ".join("0x%02x" % REV[b] for b in g)
            f.write("    { %s },\n" % rows)
        f.write("};\n\n#endif\n")

if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Lat15-VGA16.psf.gz"
    dst = sys.argv[2] if len(sys.argv) > 2 else "include/font8x16.h"
    glyphs = load_psf1(src)
    emit(glyphs, dst)
    print("wrote %s from %s" % (dst, src))
