#!/usr/bin/env python3
"""Build the NiteKernel driver store.

Indexes the vendor driver packages under tools/payloads/ into:

  * <out_dir>/store.json                  host-readable manifest
  * <out_dir>/payloads/<file>             payloads served over HTTP (the mirror)
  * src/generated/driver_store_gen.c      the same index compiled into the kernel

The kernel matches store entries against the hardware it discovers on first
boot, downloads the matching payloads over HTTP, verifies their SHA-256, and
records them in the on-disk driver database.

Usage: build_store.py <out_dir> [iso_path]
"""
import hashlib
import json
import os
import shutil
import sys

# Entry template: which hardware each payload targets.
# `class_code` follows the PCI class codes the kernel reports:
#   0x01 = storage, 0x02 = network, 0x03 = display.
DESCRIPTORS = {
    "libgl1-mesa-dri.deb": {
        "name": "mesa-dri",
        "kind": "mesa-dri",
        "vendor": "mesa",
        "class_code": 0x03,
        "vendor_id": 0,
        "device_id": 0,
        "version": "25.0.7",
        "url": "http://deb.debian.org/debian/pool/main/m/mesa/"
               "libgl1-mesa-dri_25.0.7-2%2bdeb13u1_amd64.deb",
        "priority": 20,
        "provides": "DRI/KMS userspace GPU drivers (i915, radeonsi, nouveau, ...)",
    },
    "libglx-mesa0.deb": {
        "name": "mesa-glx",
        "kind": "mesa-glx",
        "vendor": "mesa",
        "class_code": 0x03,
        "vendor_id": 0,
        "device_id": 0,
        "version": "25.0.7",
        "url": "http://deb.debian.org/debian/pool/main/m/mesa/"
               "libglx-mesa0_25.0.7-2%2bdeb13u1_amd64.deb",
        "priority": 10,
        "provides": "Mesa GLX loader for the X/GL stack",
    },
}

# The mirror the kernel is told to try first; the upstream URL is the fallback.
DEFAULT_MIRROR = "http://10.0.2.2:8080"


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def c_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    out_dir = sys.argv[1]
    payload_src = os.path.join(os.path.dirname(os.path.abspath(__file__)), "payloads")
    payload_out = os.path.join(out_dir, "payloads")
    os.makedirs(payload_out, exist_ok=True)

    entries = []
    for filename in sorted(os.listdir(payload_src)):
        path = os.path.join(payload_src, filename)
        if not os.path.isfile(path):
            continue
        desc = DESCRIPTORS.get(filename)
        if desc is None:
            print("  skip (no descriptor): %s" % filename)
            continue
        digest = sha256_file(path)
        size = os.path.getsize(path)
        shutil.copy2(path, os.path.join(payload_out, filename))
        entry = dict(desc)
        entry["file"] = filename
        entry["size"] = size
        entry["sha256"] = digest
        entries.append(entry)
        print("  indexed %-24s %8d bytes  %s" % (filename, size, digest[:16]))

    manifest = {
        "version": 1,
        "format": "nitekernel-driver-store",
        "mirror": DEFAULT_MIRROR,
        "entries": entries,
    }
    with open(os.path.join(out_dir, "store.json"), "w") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")

    # Generate the kernel-side table next to the manifest.
    gen_path = os.path.join(out_dir, "driver_store_gen.c")
    with open(gen_path, "w") as f:
        f.write("/* Generated by tools/build_store.py - do not edit by hand. */\n")
        f.write("#include <store.h>\n\n")
        f.write("const char g_store_mirror[] = \"%s\";\n\n" % c_escape(DEFAULT_MIRROR))
        f.write("const u32 g_store_count = %du;\n\n" % len(entries))
        f.write("const struct store_entry g_store_entries[] = {\n")
        for e in entries:
            f.write("    {\n")
            f.write("        .name = \"%s\",\n" % c_escape(e["name"]))
            f.write("        .kind = \"%s\",\n" % c_escape(e["kind"]))
            f.write("        .vendor = \"%s\",\n" % c_escape(e["vendor"]))
            f.write("        .file = \"%s\",\n" % c_escape(e["file"]))
            f.write("        .version = \"%s\",\n" % c_escape(e["version"]))
            f.write("        .sha256 = \"%s\",\n" % e["sha256"])
            f.write("        .url = \"%s\",\n" % c_escape(e["url"]))
            f.write("        .provides = \"%s\",\n" % c_escape(e["provides"]))
            f.write("        .size = %du,\n" % e["size"])
            f.write("        .class_code = 0x%02x,\n" % e["class_code"])
            f.write("        .vendor_id = 0x%04x,\n" % e["vendor_id"])
            f.write("        .device_id = 0x%04x,\n" % e["device_id"])
            f.write("        .priority = %d,\n" % e["priority"])
            f.write("    },\n")
        f.write("};\n")
    print("  wrote %s (%d entries)" % (gen_path, len(entries)))
    print("  wrote %s" % os.path.join(out_dir, "store.json"))


if __name__ == "__main__":
    main()
